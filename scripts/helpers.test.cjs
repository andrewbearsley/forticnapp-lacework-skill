'use strict';
// Local fixtures only. No network, credentials or tenant calls.
const assert = require('node:assert/strict');
const {parseVersions, formatVersions, decodeHtml} = require('./agent-versions.cjs');
const {pagingPath} = require('./paging-path.cjs');
const row = '<tr><td><b>1.2.3</b></td><td>Latest&nbsp;</td><td>2026-01-01</td><td>2026-05-01</td><td>2026-09-01</td></tr>';
const old = '<tr><td>1.1.0</td><td>GA</td><td>2025-12-01</td><td>Not Announced</td><td>Not Announced</td></tr>';
const fixture = '<table><tr><td>9.9.9</td><td>Latest</td></tr></table><article class="reader__page"><table><tr><th>Version</th></tr>'+row+old+'</table><table>'+row+'</table></article>';
const result = parseVersions(fixture);
assert.equal(result.latest, '1.2.3');
assert.equal(result.rows.length, 2);
assert.deepEqual(result.rows[0], {version:'1.2.3',latest:true,eoe:'2026-05-01',eos:'2026-09-01'});
assert.equal(result.rows[1].eoe, null);
const missingGa = '<article class="reader__page"><table><tr><td>3.0</td><td>Latest</td><td>Not Announced</td><td>2027-01-01</td><td>2027-02-01</td></tr></table></article>';
assert.deepEqual(parseVersions(missingGa).rows[0], {version:'3.0',latest:true,eoe:'2027-01-01',eos:'2027-02-01'});
assert.match(formatVersions('linux', result), /linux: latest=1\.2\.3/);
assert.match(formatVersions('windows', result), /Not Announced/);
assert.equal(decodeHtml('&lt;&amp;lt;&#65;&#x42;&nbsp;'), '<&lt;AB\u00a0');
assert.throws(() => parseVersions('<html>changed</html>'), /reader__page/);
assert.throws(() => parseVersions('<article class="reader__page"><table></table></article>'), /Version table/);
const eight = Array.from({length:8}, (_,i) => `<tr><td>2.${i}</td><td>${i === 0 ? 'Latest' : 'GA'}</td></tr>`).join('');
assert.equal(formatVersions('linux', parseVersions('<article class="reader__page"><table>'+eight+'</table></article>')).split('\n').length, 7);
assert.equal(pagingPath('https://tenant.lacework.net/api/v2/Hosts/cursor?q=a%20b&n=2#fragment', 'https://tenant.lacework.net'), '/api/v2/Hosts/cursor?q=a%20b&n=2');
assert.equal(pagingPath('https://tenant.lacework.net/api/v2/Hosts', 'https://tenant.lacework.net'), '/api/v2/Hosts');
assert.throws(() => pagingPath('https://other.lacework.net/api/v2/Hosts', 'https://tenant.lacework.net'), /verified HTTPS/);
assert.throws(() => pagingPath('http://tenant.lacework.net/api/v2/Hosts', 'https://tenant.lacework.net'), /verified HTTPS/);
assert.throws(() => pagingPath('https://user:pass@tenant.lacework.net/api/v2/Hosts', 'https://tenant.lacework.net'), /verified HTTPS/);
assert.throws(() => pagingPath('not-a-url', 'https://tenant.lacework.net'));
console.log('Local fixture tests passed: agent table parsing and paging URL conversion');
